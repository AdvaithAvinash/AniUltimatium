"""Appends the old-engine fallbacks (Tizen 4 = Chromium 56) to public/styles.css.
Chromium 56 has no `inset`, flex `gap`, `aspect-ratio`, `min()` or CSS grid. This script (re)generates the margin-based
replacements for every flex `gap` in the stylesheet. index.html adds html.nogap / .nogrid / .noar when a feature is missing.
Run:  python3 tools/gen_compat_css.py   (idempotent)"""
import re, os
p = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'public', 'styles.css')
MARK = '/* ===== Old-engine compatibility (generated by tools/gen_compat_css.py) ===== */'
s = open(p).read().split(MARK)[0].rstrip('\n') + '\n'
s = s.replace('inset:0', 'top:0;right:0;bottom:0;left:0')              # inset: Chrome 87+
for a, b in [('width:min(46rem,100%)', 'width:100%;max-width:46rem'), ('width:min(44rem,62%)', 'width:62%;max-width:44rem'),
             ('width:min(62rem,92vw)', 'width:92vw;max-width:62rem')]:    # min(): Chrome 79+
    s = s.replace(a, b)

def rules(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out, i, n = [], 0, len(css)
    def block(start, media):
        i = start
        while i < n:
            j = css.find('{', i); k = css.find('}', i)
            if j == -1 or (k != -1 and k < j): return k + 1
            head = css[i:j].strip()
            if head.startswith('@media') or head.startswith('@supports'):
                end = block(j + 1, head)
                i = end
            elif head.startswith('@'):                      # @keyframes, @font-face ...: skip the balanced block
                depth, e = 1, j + 1
                while depth and e < n:
                    depth += (css[e] == '{') - (css[e] == '}'); e += 1
                i = e
            else:
                end = css.find('}', j)
                out.append((media, head, css[j + 1:end].strip()))
                i = end + 1
        return n
    block(0, None)
    return out

fb, med = [], {}
for media, sel, body in rules(s):
    if sel.startswith('@') or sel in ('.cards', '#dEps', '.ngrid') or re.search(r'display:\s*grid', body): continue
    m = re.search(r'(?:^|;)\s*gap:([^;]+)', body)
    if not m: continue
    vals = m.group(1).split(); row, col = (vals[0], vals[1]) if len(vals) == 2 else (vals[0], vals[0])
    for one in [x.strip() for x in sel.split(',')]:
        if 'flex-wrap:wrap' in body: r = f'.nogap {one}>*{{margin:0 {col} {row} 0}}'
        elif 'flex-direction:column' in body: r = f'.nogap {one}>*+*{{margin-top:{row}}}'
        else: r = f'.nogap {one}>*+*{{margin-left:{col}}}'
        (med.setdefault(media, []) if media else fb).append(r)
block = [MARK, '/* index.html adds html.nogap / .nogrid / .noar when the browser lacks flex gap, CSS grid or aspect-ratio */'] + fb
for m, rs in med.items(): block.append(m + '{' + ''.join(rs) + '}')
block += ['.noar .poster{height:0;padding-top:150%}', '.noar .poster img{position:absolute;top:0;left:0}',
          '.nogrid .cards{display:flex;flex-wrap:wrap;justify-content:flex-start}', '.nogrid .cards .card{margin:0 1.2rem 1.6rem 0}',
          '.nogrid #dEps{display:flex;flex-wrap:wrap}', '.nogrid #dEps .ep{width:8rem;margin:0 .9rem .9rem 0}',
          '.nogrid .ngrid{display:flex;flex-wrap:wrap}', '.nogrid .ngrid div{width:48.5%;margin:0 1% .8rem 0;box-sizing:border-box}',
          '@media (max-width:820px){.nogrid .ngrid div{width:100%}}']
open(p, 'w').write(s + '\n'.join(block) + '\n')
print(len(fb), 'flex-gap fallbacks;', {k: len(v) for k, v in med.items()})
